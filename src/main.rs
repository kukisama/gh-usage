// Only normalize the leading convenience spelling. Never rewrite option values
// (e.g. --hostname -view) or anything following the `--` separator.
fn normalize_view_args(
    args: impl IntoIterator<Item = impl Into<std::ffi::OsString>>,
) -> Vec<std::ffi::OsString> {
    let mut args: Vec<_> = args.into_iter().map(Into::into).collect();
    if let Some(arg) = args.get_mut(1)
        && arg == "-view"
    {
        *arg = "--view".into();
    }
    args
}

fn resolve_html_path(cli: &Cli, output: &Path, hostname: &str) -> Option<PathBuf> {
    if cli.no_html {
        None
    } else if let Some(path) = &cli.html {
        Some(path.clone())
    } else if output.as_os_str() == "-" {
        cli.view.then(|| PathBuf::from(format!("copilot-usage-{hostname}.html")))
    } else {
        Some(default_html_path(output, hostname))
    }
}

fn main() -> Result<()> {
    let total_started = Instant::now();
    let no_args = env::args_os().len() == 1;
    // Treat this as a true double-click only when launched directly from
    // Explorer (parent process is explorer.exe). Terminal runs, CI, and the
    // winget package-validation sandbox all have a different parent process, so
    // they skip the keypress pause entirely and exit cleanly after writing the
    // report files. This is what keeps automated installation verification from
    // hanging on `wait_for_any_key()`.
    let double_clicked = no_args && launched_from_explorer();
    let cli = Cli::parse_from(normalize_view_args(env::args_os()));

    if let Some(dir) = cli.merge.clone() {
        return run_merge(&dir, double_clicked, cli.view, cli.html.as_deref());
    }

    let hostname = cli
        .hostname
        .clone()
        .map(|name| sanitize_hostname(&name))
        .unwrap_or_else(detect_hostname);

    let output_path = cli
        .output
        .clone()
        .unwrap_or_else(|| default_output_path(&hostname, cli.format));

    let html_path = resolve_html_path(&cli, &output_path, &hostname);

    let vscode_root = cli
        .vscode_workspace_storage
        .or_else(default_vscode_workspace_storage)
        .context(
            "Could not determine VS Code workspaceStorage path; pass --vscode-workspace-storage",
        )?;

    let copilot_cli_root = cli.copilot_cli_root.or_else(default_copilot_cli_root);
    let cutoff = cli.since_days.map(cutoff_system_time);

    let mut files = collect_vscode_chat_session_files(&vscode_root, cutoff.as_ref())?;
    let mut cli_database_result = None;

    if (!cli.no_cli_logs || cli.include_cli_logs)
        && let Some(root) = copilot_cli_root.as_ref()
    {
        match scan_cli_usage_database(root, cutoff.as_ref()) {
            Ok(Some(result)) => cli_database_result = Some(result),
            Ok(None) => files.extend(collect_cli_probe_files(root, cutoff.as_ref())?),
            Err(error) => {
                eprintln!(
                    "warning: could not read Copilot CLI session store ({error:#}); falling back to logs"
                );
                files.extend(collect_cli_probe_files(root, cutoff.as_ref())?);
            }
        }
    }

    files.sort();
    files.dedup();

    if let Some(max_files) = cli.max_files {
        files.truncate(max_files);
    }
    let scanned_files = files.len() + usize::from(cli_database_result.is_some());
    let project_map = build_project_map(&files);
    let mut file_results: Vec<FileScanResult> = files
        .par_iter()
        .map(|path| scan_file(path, &project_map))
        .collect();
    if let Some(result) = cli_database_result {
        file_results.push(result);
    }
    let mut stats = ScanStats {
        scanned_files,
        ..ScanStats::default()
    };
    let mut records = Vec::new();

    for result in file_results {
        stats.scanned_lines += result.scanned_lines;
        stats.json_candidate_lines += result.json_candidate_lines;
        stats.parse_errors += result.parse_errors;
        records.extend(result.records);
    }

    records.sort_by(|a, b| {
        a.timestamp_ms
            .cmp(&b.timestamp_ms)
            .then_with(|| a.file.cmp(&b.file))
            .then_with(|| a.line.cmp(&b.line))
            .then_with(|| a.response_id.cmp(&b.response_id))
    });
    records.dedup_by(|a, b| {
        a.file == b.file
            && a.line == b.line
            && a.request_id == b.request_id
            && a.turn_index == b.turn_index
            && a.response_id == b.response_id
            && a.details == b.details
    });
    for record in &mut records {
        record.hostname = hostname.clone();
    }
    assign_turn_indices(&mut records);

    match cli.format {
        OutputFormat::Csv => write_csv(&output_path, &records, !cli.no_bom)?,
        OutputFormat::Json => write_json(&output_path, &records, !cli.no_bom)?,
    }
    if let Some(html_path) = html_path.as_ref() {
        write_html(html_path, &records, &hostname)?;
    }
    let total_ms = total_started.elapsed().as_millis();

    if no_args || cli.summary {
        let report = build_summary_report(
            &output_path,
            html_path.as_deref(),
            &records,
            &stats,
            total_ms,
        );
        if output_path.as_os_str() == "-" {
            eprint!("{report}");
        } else {
            print!("{report}");
        }
    }

    if cli.view {
        open_path(html_path.as_deref().context("--view requires HTML output")?)?;
    } else if double_clicked && console_is_interactive() {
        show_double_click_exit_notice(&output_path, html_path.as_deref());
    }

    Ok(())
}

/// Returns true only when the program is attached to a real interactive
/// console. In non-interactive environments (CI, piped/redirected I/O, the
/// winget installation-verification sandbox) stdin is not a terminal, so we
/// must not pause for a keypress or implicitly open the browser. An explicit
/// --view request is handled separately and never waits for a keypress.
fn console_is_interactive() -> bool {
    std::io::stdin().is_terminal() && std::io::stdout().is_terminal()
}

fn show_double_click_exit_notice(output: &Path, html: Option<&Path>) {
    println!();
    println!(
        "CSV saved to {}",
        output.display()
    );
    println!(
        "  Every parsed Copilot usage record is in there - import it into Excel,"
    );
    println!(
        "  Power BI, or pipe it through your own scripts for deeper analysis."
    );
    if let Some(html) = html {
        println!();
        println!("HTML report saved to {}", html.display());
        println!(
            "  A self-contained, offline-friendly page with charts, host/model"
        );
        println!(
            "  filters, and a paginated record table. Safe to email or archive."
        );
        // Open the report automatically so viewing it never requires a keypress.
        // This branch only runs on a genuine Explorer double-click; terminal,
        // CI, and the winget validation sandbox never reach here.
        if let Err(error) = open_path(html) {
            eprintln!("warning: {error:#}");
        }
        println!();
        println!(">> The report is ready to view.");
        println!("   If it didn't open, double-click the HTML file above, or run");
        println!("   `gh-usage --html <PATH>` to regenerate it at a path you choose.");
    } else {
        println!();
        println!("HTML report skipped (--no-html). The CSV above is your full dataset.");
        println!("   Re-run without --no-html (or `gh-usage --html <PATH>`) to build it.");
    }
    println!();
    println!(">> Press any key to close this window. Your files are already saved.");
    wait_for_any_key();
}

fn open_path(path: &Path) -> Result<()> {
    // Absolute paths avoid interpreting filenames as launcher options. Do not
    // canonicalize: Windows extended-length paths can confuse shell handlers.
    let absolute = std::path::absolute(path)?;
    anyhow::ensure!(absolute.is_file(), "HTML report not found: {}", absolute.display());
    open::that(&absolute).with_context(|| {
        format!("HTML saved to {}, but could not launch its default browser", absolute.display())
    })?;
    // Keep stdout clean for --output - and report only the launch request,
    // not a browser-rendering success that we cannot observe here.
    eprintln!("Requested browser opening: {}", absolute.display());
    Ok(())
}

// Detects whether the process was launched by double-clicking the executable
// in Windows Explorer (parent process is explorer.exe). We use this to gate the
// keypress pause so only genuine double-clicks wait for a key; terminal, CI, and
// the winget validation sandbox have a different parent and exit immediately.
#[cfg(windows)]
fn launched_from_explorer() -> bool {
    windows_parent_process_name()
        .as_deref()
        .is_some_and(|name| name.eq_ignore_ascii_case("explorer.exe"))
}

#[cfg(not(windows))]
fn launched_from_explorer() -> bool {
    false
}

#[cfg(windows)]
fn wait_for_any_key() {
    use windows_sys::Win32::Foundation::INVALID_HANDLE_VALUE;
    use windows_sys::Win32::System::Console::{
        GetConsoleMode, GetStdHandle, ReadConsoleW, SetConsoleMode, ENABLE_ECHO_INPUT,
        ENABLE_LINE_INPUT, STD_INPUT_HANDLE,
    };

    unsafe {
        let handle = GetStdHandle(STD_INPUT_HANDLE);
        if handle == INVALID_HANDLE_VALUE {
            return;
        }

        let mut original_mode = 0;
        if GetConsoleMode(handle, &mut original_mode) == 0 {
            let mut input = String::new();
            let _ = std::io::stdin().read_line(&mut input);
            return;
        }

        let single_key_mode = original_mode & !(ENABLE_LINE_INPUT | ENABLE_ECHO_INPUT);
        let _ = SetConsoleMode(handle, single_key_mode);

        let mut buffer = [0u16; 1];
        let mut chars_read = 0;
        let _ = ReadConsoleW(
            handle,
            buffer.as_mut_ptr().cast(),
            buffer.len() as u32,
            &mut chars_read,
            std::ptr::null_mut(),
        );

        let _ = SetConsoleMode(handle, original_mode);
    }
}

#[cfg(not(windows))]
fn wait_for_any_key() {}

#[cfg(windows)]
fn windows_parent_process_name() -> Option<String> {
    use windows_sys::Win32::Foundation::{CloseHandle, INVALID_HANDLE_VALUE};
    use windows_sys::Win32::System::Diagnostics::ToolHelp::{
        CreateToolhelp32Snapshot, Process32FirstW, Process32NextW, PROCESSENTRY32W,
        TH32CS_SNAPPROCESS,
    };

    unsafe {
        let snapshot = CreateToolhelp32Snapshot(TH32CS_SNAPPROCESS, 0);
        if snapshot == INVALID_HANDLE_VALUE {
            return None;
        }

        let mut entry = std::mem::zeroed::<PROCESSENTRY32W>();
        entry.dwSize = std::mem::size_of::<PROCESSENTRY32W>() as u32;

        let current_pid = std::process::id();
        let mut parent_pid = None;

        if Process32FirstW(snapshot, &mut entry) != 0 {
            loop {
                if entry.th32ProcessID == current_pid {
                    parent_pid = Some(entry.th32ParentProcessID);
                    break;
                }

                if Process32NextW(snapshot, &mut entry) == 0 {
                    break;
                }
            }
        }

        let Some(parent_pid) = parent_pid else {
            let _ = CloseHandle(snapshot);
            return None;
        };

        if Process32FirstW(snapshot, &mut entry) != 0 {
            loop {
                if entry.th32ProcessID == parent_pid {
                    let name = wide_process_name_to_string(&entry.szExeFile);
                    let _ = CloseHandle(snapshot);
                    return name;
                }

                if Process32NextW(snapshot, &mut entry) == 0 {
                    break;
                }
            }
        }

        let _ = CloseHandle(snapshot);
        None
    }
}

#[cfg(windows)]
#[allow(dead_code)]
fn wide_process_name_to_string(buffer: &[u16]) -> Option<String> {
    let len = buffer.iter().position(|ch| *ch == 0).unwrap_or(buffer.len());
    if len == 0 {
        None
    } else {
        Some(String::from_utf16_lossy(&buffer[..len]))
    }
}

/// Merge mode: read every `copilot-usage-*.csv` in `dir`, combine + dedupe,
/// render a single `copilot-usage-merged.html` next to those CSVs.
fn run_merge(dir: &Path, double_clicked: bool, view: bool, html: Option<&Path>) -> Result<()> {
    if !dir.is_dir() {
        anyhow::bail!(
            "merge target is not a directory: {}",
            dir.display()
        );
    }

    let mut csv_files: Vec<PathBuf> = Vec::new();
    for entry in fs::read_dir(dir)
        .with_context(|| format!("read_dir failed for {}", dir.display()))?
    {
        let entry = entry?;
        let path = entry.path();
        if !path.is_file() {
            continue;
        }
        let name = match path.file_name().and_then(|s| s.to_str()) {
            Some(n) => n,
            None => continue,
        };
        let lower = name.to_ascii_lowercase();
        if !lower.starts_with("copilot-usage-") || !lower.ends_with(".csv") {
            continue;
        }
        // Skip our own merged outputs so re-running is idempotent.
        if lower == "copilot-usage-merged.csv" {
            continue;
        }
        csv_files.push(path);
    }
    csv_files.sort();

    if csv_files.is_empty() {
        anyhow::bail!(
            "no copilot-usage-*.csv files found in {}",
            dir.display()
        );
    }

    let mut records: Vec<UsageRecord> = Vec::new();
    let mut per_file: Vec<(PathBuf, usize)> = Vec::new();
    let mut row_errors: usize = 0;
    for path in &csv_files {
        let before = records.len();
        let mut reader = csv::ReaderBuilder::new()
            .flexible(true)
            .from_path(path)
            .with_context(|| format!("open csv {}", path.display()))?;
        for row in reader.deserialize::<UsageRecord>() {
            match row {
                Ok(record) => records.push(record),
                Err(_) => row_errors += 1,
            }
        }
        per_file.push((path.clone(), records.len() - before));
    }

    // Backfill hostname for legacy CSVs (pre-hostname column) using the file stem.
    for (path, _) in &per_file {
        let stem = path
            .file_stem()
            .and_then(|s| s.to_str())
            .unwrap_or_default();
        if let Some(host_from_name) = stem.strip_prefix("copilot-usage-") {
            for record in records.iter_mut().filter(|r| r.hostname.is_empty()) {
                record.hostname = host_from_name.to_owned();
            }
        }
    }

    records.sort_by(|a, b| {
        a.hostname
            .cmp(&b.hostname)
            .then_with(|| a.timestamp_ms.cmp(&b.timestamp_ms))
            .then_with(|| a.file.cmp(&b.file))
            .then_with(|| a.line.cmp(&b.line))
            .then_with(|| a.response_id.cmp(&b.response_id))
    });
    records.dedup_by(|a, b| {
        a.hostname == b.hostname
            && a.file == b.file
            && a.line == b.line
            && a.request_id == b.request_id
            && a.turn_index == b.turn_index
            && a.response_id == b.response_id
            && a.details == b.details
    });
    assign_turn_indices(&mut records);

    let hosts: std::collections::BTreeSet<String> =
        records.iter().map(|r| r.hostname.clone()).collect();
    let primary_host = hosts
        .iter()
        .next()
        .cloned()
        .unwrap_or_else(|| "merged".to_owned());

    let html_path = html.map(Path::to_path_buf)
        .unwrap_or_else(|| dir.join("copilot-usage-merged.html"));
    write_html(&html_path, &records, &primary_host)?;

    // Compact merge summary, mirroring the look of the regular scan report.
    const INNER: usize = 54;
    let row = |content: String| -> String {
        let len = content.chars().count();
        let padded = if len < INNER {
            format!("{content}{}", " ".repeat(INNER - len))
        } else {
            content.chars().take(INNER).collect()
        };
        format!("| {padded} |\n")
    };
    let header = |title: &str| -> String {
        let prefix = format!("- {title} ");
        let pad = (INNER + 2).saturating_sub(prefix.chars().count());
        format!("+{prefix}{}+\n", "-".repeat(pad))
    };
    let plain_border = || -> String { format!("+{}+\n", "-".repeat(INNER + 2)) };

    let total_credits = normalize_zero(records.iter().map(|r| r.credits).sum());
    let host_list: Vec<&str> = hosts.iter().map(String::as_str).collect();

    let mut out = String::new();
    out.push_str(&header("GitHub Copilot Usage - Merge"));
    out.push_str(&row(format!(
        "{:<14}{:>12}  {:<14}{:>12}",
        "csv files",
        csv_files.len(),
        "row errors",
        row_errors
    )));
    out.push_str(&row(format!(
        "{:<14}{:>12}  {:<14}{:>12}",
        "records",
        records.len(),
        "hosts",
        hosts.len()
    )));
    out.push_str(&row(format!(
        "{:<14}{:>12}  {:<14}{:>12}",
        "total credits",
        format!("{:.1}", total_credits),
        "target dir",
        clip(&dir.display().to_string(), 12)
    )));

    out.push_str(&header("Sources"));
    for (path, count) in &per_file {
        let file_name = path
            .file_name()
            .and_then(|s| s.to_str())
            .unwrap_or("<unknown>");
        out.push_str(&row(format!(
            "{:<40}{:>14}",
            clip(file_name, 40),
            format!("{count} rows")
        )));
    }

    out.push_str(&header("Hosts"));
    out.push_str(&row(clip(&host_list.join(", "), INNER)));

    out.push_str(&header("Output"));
    out.push_str(&row(format!(
        "html  {}",
        clip(&html_path.display().to_string(), INNER - 6)
    )));
    out.push_str(&plain_border());
    print!("{out}");

    if view {
        open_path(&html_path)?;
    } else if double_clicked && console_is_interactive() {
        show_merge_exit_notice(&html_path, &host_list);
    }
    Ok(())
}

