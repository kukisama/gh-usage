fn collect_vscode_chat_session_files(
    root: &Path,
    cutoff: Option<&std::time::SystemTime>,
) -> Result<Vec<PathBuf>> {
    if !root.exists() {
        return Ok(Vec::new());
    }

    let mut files = Vec::new();
    for workspace_entry in fs::read_dir(root)? {
        let Ok(workspace_entry) = workspace_entry else {
            continue;
        };
        let Ok(file_type) = workspace_entry.file_type() else {
            continue;
        };
        if !file_type.is_dir() {
            continue;
        }

        let chat_sessions = workspace_entry.path().join("chatSessions");
        let Ok(session_entries) = fs::read_dir(chat_sessions) else {
            continue;
        };

        for session_entry in session_entries {
            let Ok(session_entry) = session_entry else {
                continue;
            };
            let path = session_entry.path();
            if path.extension().and_then(|extension| extension.to_str()) != Some("jsonl") {
                continue;
            }
            if !modified_after(&path, cutoff) {
                continue;
            }
            files.push(path);
        }
    }

    Ok(files)
}

fn collect_cli_probe_files(
    root: &Path,
    cutoff: Option<&std::time::SystemTime>,
) -> Result<Vec<PathBuf>> {
    if !root.exists() {
        return Ok(Vec::new());
    }

    let files = WalkDir::new(root)
        .follow_links(false)
        .into_iter()
        .filter_map(Result::ok)
        .filter(|entry| entry.file_type().is_file())
        .filter(|entry| {
            matches!(
                entry
                    .path()
                    .extension()
                    .and_then(|extension| extension.to_str()),
                Some("jsonl" | "json" | "log")
            )
        })
        .filter(|entry| {
            has_component(entry.path(), "session-state") || has_component(entry.path(), "logs")
        })
        .filter(|entry| modified_after(entry.path(), cutoff))
        .map(|entry| entry.into_path())
        .collect();

    Ok(files)
}

/// Correlates Copilot CLI `events.jsonl` traces with the precise usage ledger.
/// Newer CLI builds persist every model call in `assistant_usage_events`,
/// including calls from an active session, while JSONL remains the report's
/// traceable source path. Returning `None` means this is an older store and the
/// caller should use the generic JSONL/log probe instead.
fn scan_cli_usage_database(
    root: &Path,
    cutoff: Option<&std::time::SystemTime>,
) -> Result<Option<FileScanResult>> {
    let path = root.join("session-store.db");
    if !path.is_file() {
        return Ok(None);
    }

    let connection = Connection::open_with_flags(
        &path,
        OpenFlags::SQLITE_OPEN_READ_ONLY | OpenFlags::SQLITE_OPEN_NO_MUTEX,
    )
    .with_context(|| format!("open Copilot CLI database {}", path.display()))?;

    let has_usage_table: bool = connection
        .query_row(
            "SELECT EXISTS(SELECT 1 FROM sqlite_master WHERE type = 'table' AND name = 'assistant_usage_events')",
            [],
            |row| row.get(0),
        )
        .with_context(|| format!("inspect Copilot CLI database {}", path.display()))?;
    if !has_usage_table {
        return Ok(None);
    }

    let cutoff_ms = cutoff.and_then(system_time_to_unix_ms);
    scan_cli_usage_connection(&connection, &path, cutoff_ms).map(Some)
}

fn scan_cli_usage_connection(
    connection: &Connection,
    source_path: &Path,
    cutoff_ms: Option<i64>,
) -> Result<FileScanResult> {
    const NANO_AIU_PER_CREDIT: f64 = 1_000_000_000.0;
    let mut result = FileScanResult::default();
    let cli_root = source_path.parent().unwrap_or_else(|| Path::new(""));
    let mut session_events = load_cli_session_events(cli_root);
    result.scanned_lines += session_events
        .values()
        .map(|events| events.scanned_lines)
        .sum::<usize>();
    let query =
        "SELECT u.session_id, u.turn_index, u.model, u.total_nano_aiu,
                u.duration_ms, u.created_at, u.agent_id
         FROM assistant_usage_events u
         WHERE u.total_nano_aiu IS NOT NULL AND u.total_nano_aiu > 0
         ORDER BY u.session_id, u.turn_index, u.model, u.created_at, u.id";
    let mut statement = connection.prepare(query)?;
    let rows = statement.query_map([], |row| {
        Ok((
            row.get::<_, String>(0)?,
            row.get::<_, Option<i64>>(1)?,
            row.get::<_, String>(2)?,
            row.get::<_, i64>(3)?,
            row.get::<_, Option<i64>>(4)?,
            row.get::<_, String>(5)?,
            row.get::<_, Option<String>>(6)?,
        ))
    })?;

    let mut aggregates: BTreeMap<(String, Option<u32>, String), CliUsageAggregate> =
        BTreeMap::new();
    let mut sessions_with_database_usage = HashSet::new();
    for row in rows {
        result.scanned_lines += 1;
        result.json_candidate_lines += 1;
        let (
            session_id,
            zero_based_turn,
            model,
            total_nano_aiu,
            duration_ms,
            created_at,
            agent_id,
        ) = row?;
        let Some(completed_at_ms) = parse_rfc3339_timestamp_ms(&created_at) else {
            result.parse_errors += 1;
            continue;
        };
        let Some((record_source_path, record_source_line, event_timestamp_ms)) =
            match_cli_event_message(
            &mut session_events,
            &session_id,
            completed_at_ms,
            &model,
            agent_id_is_present(&agent_id),
        )
        else {
            continue;
        };
        sessions_with_database_usage.insert(session_id.clone());
        if cutoff_ms.is_some_and(|cutoff| event_timestamp_ms < cutoff) {
            continue;
        }

        let (title, project) = session_events
            .get(&session_id)
            .map(|events| (events.title.clone(), events.project.clone()))
            .unwrap_or_default();
        let turn_index = zero_based_turn.and_then(|turn| {
            turn.checked_add(1)
                .and_then(|turn| u32::try_from(turn).ok())
        });
        let key = (session_id.clone(), turn_index, model.clone());
        let duration_ms = duration_ms.unwrap_or_default().max(0);
        let started_at_ms = event_timestamp_ms.saturating_sub(duration_ms);

        let entry = aggregates.entry(key).or_insert_with(|| CliUsageAggregate {
            source_path: record_source_path.clone(),
            source_line: record_source_line,
            session_id,
            turn_index,
            model,
            credits: 0.0,
            request_count: 0,
            started_at_ms,
            completed_at_ms: event_timestamp_ms,
            title: title.clone(),
            project: project.clone(),
        });
        if record_source_line < entry.source_line {
            entry.source_path = record_source_path;
            entry.source_line = record_source_line;
        }
        entry.credits += total_nano_aiu as f64 / NANO_AIU_PER_CREDIT;
        entry.request_count += 1;
        entry.started_at_ms = entry.started_at_ms.min(started_at_ms);
        entry.completed_at_ms = entry.completed_at_ms.max(event_timestamp_ms);
        if entry.title.is_none() {
            entry.title = title;
        }
        if entry.project.is_none() {
            entry.project = project;
        }
    }

    let mut session_totals: HashMap<String, u32> = HashMap::new();
    for aggregate in aggregates.values() {
        if let Some(turn) = aggregate.turn_index {
            session_totals
                .entry(aggregate.session_id.clone())
                .and_modify(|total| *total = (*total).max(turn))
                .or_insert(turn);
        }
    }

    for aggregate in aggregates.into_values() {
        let duration_ms = aggregate
            .completed_at_ms
            .saturating_sub(aggregate.started_at_ms);
        let details = format!(
            "Copilot CLI {} ({} model call{}) • {} credits",
            aggregate.model,
            aggregate.request_count,
            if aggregate.request_count == 1 {
                ""
            } else {
                "s"
            },
            aggregate.credits
        );
        result.records.push(UsageRecord {
            source: "copilot.cli.events".to_owned(),
            hostname: String::new(),
            timestamp_ms: Some(aggregate.completed_at_ms),
            local_time_hint: format_local_time(aggregate.completed_at_ms),
            chat_title: aggregate.title,
            model: aggregate.model.clone(),
            model_id: Some(aggregate.model),
            credits: aggregate.credits,
            details,
            session_id: Some(aggregate.session_id.clone()),
            request_id: None,
            response_id: None,
            agent_id: None,
            project: aggregate.project,
            duration_ms: (duration_ms > 0).then_some(duration_ms),
            turn_index: aggregate.turn_index,
            session_total: session_totals.get(&aggregate.session_id).copied(),
            file: aggregate.source_path.to_string_lossy().into_owned(),
            line: aggregate.source_line,
        });
    }

    append_legacy_cli_shutdown_records(
        &mut result,
        &session_events,
        &sessions_with_database_usage,
        cutoff_ms,
    );

    Ok(result)
}

fn agent_id_is_present(agent_id: &Option<String>) -> bool {
    agent_id.as_ref().is_some_and(|agent| !agent.is_empty())
}

fn load_cli_session_events(root: &Path) -> HashMap<String, CliSessionEvents> {
    let session_root = root.join("session-state");
    let Ok(entries) = fs::read_dir(session_root) else {
        return HashMap::new();
    };
    let mut sessions = HashMap::new();
    for entry in entries.flatten() {
        let Ok(file_type) = entry.file_type() else {
            continue;
        };
        if !file_type.is_dir() {
            continue;
        }
        let session_id = entry.file_name().to_string_lossy().into_owned();
        let path = entry.path().join("events.jsonl");
        if let Some(events) = read_cli_session_events(&path) {
            sessions.insert(session_id, events);
        }
    }
    sessions
}

fn read_cli_session_events(path: &Path) -> Option<CliSessionEvents> {
    let file = File::open(path).ok()?;
    let workspace = path
        .parent()
        .map(read_cli_workspace_metadata)
        .unwrap_or_default();
    let mut events = CliSessionEvents {
        path: path.to_path_buf(),
        title: workspace.title,
        project: workspace.project,
        ..CliSessionEvents::default()
    };
    let reader = BufReader::with_capacity(1024 * 1024, file);
    for (index, line) in reader.split(b'\n').enumerate() {
        events.scanned_lines += 1;
        let Ok(line) = line else {
            continue;
        };
        let Ok(value) = serde_json::from_slice::<Value>(&line) else {
            continue;
        };
        let Some(object) = value.as_object() else {
            continue;
        };
        let Some(timestamp_ms) = object
            .get("timestamp")
            .and_then(Value::as_str)
            .and_then(parse_rfc3339_timestamp_ms)
        else {
            continue;
        };
        let line_number = index + 1;
        let event_type = object.get("type").and_then(Value::as_str);
        let data = object.get("data").and_then(Value::as_object);
        if event_type == Some("user.message") && events.title.is_none() {
            let is_root_user_message = object
                .get("agentId")
                .and_then(Value::as_str)
                .is_none_or(str::is_empty)
                && data
                    .and_then(|data| data.get("source"))
                    .is_none_or(Value::is_null);
            if is_root_user_message {
                events.title = data
                    .and_then(|data| data.get("content"))
                    .and_then(Value::as_str)
                    .and_then(|content| normalized_cli_title(Some(content)));
            }
        } else if event_type == Some("assistant.message") {
            let Some(data) = data else {
                continue;
            };
            let Some(model) = data.get("model").and_then(Value::as_str) else {
                continue;
            };
            let Some(api_call_id) = data.get("apiCallId").and_then(Value::as_str) else {
                continue;
            };
            events.messages.push(CliEventMessage {
                line: line_number,
                timestamp_ms,
                model: model.to_owned(),
                is_subagent: object
                    .get("agentId")
                    .and_then(Value::as_str)
                    .is_some_and(|agent| !agent.is_empty()),
                api_call_id: api_call_id.to_owned(),
            });
        } else if event_type == Some("session.shutdown") {
            let Some(model_metrics) = data
                .and_then(|data| data.get("modelMetrics"))
                .and_then(Value::as_object)
            else {
                continue;
            };
            for (model, metrics) in model_metrics {
                let Some(credits) = metrics
                    .get("requests")
                    .and_then(|requests| requests.get("cost"))
                    .and_then(value_as_f64)
                else {
                    continue;
                };
                if credits > 0.0 {
                    events.shutdown_metrics.push(CliShutdownMetric {
                        line: line_number,
                        timestamp_ms,
                        model: model.clone(),
                        credits,
                    });
                }
            }
        }
    }
    Some(events)
}

fn read_cli_workspace_metadata(session_dir: &Path) -> CliWorkspaceMetadata {
    let Ok(workspace) = fs::read_to_string(session_dir.join("workspace.yaml")) else {
        return CliWorkspaceMetadata::default();
    };
    let mut name = None;
    let mut cwd = None;
    for line in workspace.lines().filter(|line| !line.starts_with(char::is_whitespace)) {
        if let Some(value) = line.strip_prefix("name:").and_then(cli_yaml_scalar) {
            name = Some(value);
        } else if let Some(value) = line.strip_prefix("cwd:").and_then(cli_yaml_scalar) {
            cwd = Some(value);
        }
    }
    CliWorkspaceMetadata {
        title: name.as_deref().and_then(|name| normalized_cli_title(Some(name))),
        project: cwd.as_deref().and_then(project_name_from_cli_path),
    }
}

fn cli_yaml_scalar(raw: &str) -> Option<String> {
    let value = raw.trim();
    if value.is_empty() {
        return None;
    }
    if value.starts_with('"') && value.ends_with('"') {
        return serde_json::from_str::<String>(value).ok();
    }
    let value = value
        .strip_prefix('\'')
        .and_then(|value| value.strip_suffix('\''))
        .unwrap_or(value)
        .replace("''", "'");
    (!value.is_empty()).then_some(value)
}

fn match_cli_event_message(
    sessions: &mut HashMap<String, CliSessionEvents>,
    session_id: &str,
    timestamp_ms: i64,
    model: &str,
    is_subagent: bool,
) -> Option<(PathBuf, usize, i64)> {
    const MAX_TIMESTAMP_DELTA_MS: i64 = 1_000;
    let events = sessions.get_mut(session_id)?;
    let find_nearest = |require_agent_match: bool, events: &CliSessionEvents| {
        events
            .messages
            .iter()
            .enumerate()
            .filter(|(_, message)| {
                message.model == model
                    && !events.used_api_calls.contains(&message.api_call_id)
                    && (!require_agent_match || message.is_subagent == is_subagent)
            })
            .min_by_key(|(_, message)| message.timestamp_ms.abs_diff(timestamp_ms))
            .map(|(index, message)| (index, message.timestamp_ms.abs_diff(timestamp_ms)))
    };
    let (index, delta) = find_nearest(true, events).or_else(|| find_nearest(false, events))?;
    if delta > u64::try_from(MAX_TIMESTAMP_DELTA_MS).ok()? {
        return None;
    }
    let message = &events.messages[index];
    events.used_api_calls.insert(message.api_call_id.clone());
    Some((events.path.clone(), message.line, message.timestamp_ms))
}

fn append_legacy_cli_shutdown_records(
    result: &mut FileScanResult,
    session_events: &HashMap<String, CliSessionEvents>,
    sessions_with_database_usage: &HashSet<String>,
    cutoff_ms: Option<i64>,
) {
    for (session_id, events) in session_events {
        if sessions_with_database_usage.contains(session_id) {
            continue;
        }
        for metric in &events.shutdown_metrics {
            if cutoff_ms.is_some_and(|cutoff| metric.timestamp_ms < cutoff) {
                continue;
            }
            result.json_candidate_lines += 1;
            result.records.push(UsageRecord {
                source: "copilot.cli.events".to_owned(),
                hostname: String::new(),
                timestamp_ms: Some(metric.timestamp_ms),
                local_time_hint: format_local_time(metric.timestamp_ms),
                chat_title: events.title.clone(),
                model: metric.model.clone(),
                model_id: Some(metric.model.clone()),
                credits: metric.credits,
                details: format!(
                    "Copilot CLI {} (legacy session shutdown) • {} credits",
                    metric.model, metric.credits
                ),
                session_id: Some(session_id.clone()),
                request_id: None,
                response_id: None,
                agent_id: None,
                project: events.project.clone(),
                duration_ms: None,
                turn_index: None,
                session_total: None,
                file: events.path.to_string_lossy().into_owned(),
                line: metric.line,
            });
        }
    }
}

fn system_time_to_unix_ms(time: &std::time::SystemTime) -> Option<i64> {
    let millis = time.duration_since(std::time::UNIX_EPOCH).ok()?.as_millis();
    i64::try_from(millis).ok()
}

fn project_name_from_cli_path(path: &str) -> Option<String> {
    path.trim()
        .trim_end_matches(['/', '\\'])
        .rsplit(['/', '\\'])
        .find(|part| !part.trim().is_empty())
        .map(str::trim)
        .filter(|part| !part.is_empty())
        .map(ToOwned::to_owned)
}

fn normalized_cli_title(value: Option<&str>) -> Option<String> {
    let value = value?.lines().find(|line| !line.trim().is_empty())?.trim();
    if value.is_empty() {
        return None;
    }
    const MAX_CHARS: usize = 120;
    let mut title: String = value.chars().take(MAX_CHARS).collect();
    if value.chars().count() > MAX_CHARS {
        title.push('…');
    }
    Some(title)
}

fn has_component(path: &Path, wanted: &str) -> bool {
    path.components().any(|component| {
        component
            .as_os_str()
            .to_string_lossy()
            .eq_ignore_ascii_case(wanted)
    })
}

fn modified_after(path: &Path, cutoff: Option<&std::time::SystemTime>) -> bool {
    match cutoff {
        Some(cutoff) => path
            .metadata()
            .and_then(|metadata| metadata.modified())
            .is_ok_and(|modified| modified >= *cutoff),
        None => true,
    }
}

fn scan_file(path: &Path, project_map: &HashMap<PathBuf, String>) -> FileScanResult {
    if has_component(path, "chatSessions") {
        let project = workspace_dir_for_session(path)
            .and_then(|dir| project_map.get(&dir).cloned());
        return vscode::scan(path, project);
    }
    let mut result = FileScanResult::default();

    let Ok(file) = File::open(path) else {
        result.parse_errors += 1;
        return result;
    };

    let source = if has_component(path, "chatSessions") {
        "vscode.chatSessions"
    } else {
        "copilot.cli.probe"
    };

    let cli_workspace = (source == "copilot.cli.probe")
        .then(|| path.parent())
        .flatten()
        .map(read_cli_workspace_metadata)
        .unwrap_or_default();
    let project = workspace_dir_for_session(path)
        .and_then(|dir| project_map.get(&dir).cloned())
        .or(cli_workspace.project);
    let cli_session_id = (source == "copilot.cli.probe")
        .then(|| cli_session_id_from_event_path(path))
        .flatten();

    let mut reader = BufReader::with_capacity(1024 * 1024, file);
    let mut custom_title = cli_workspace.title;
    let mut weak_title: Option<String> = None;
    // VS Code chatSessions JSONL is a state-change log, not an append-only
    // event ledger. The same request result can be persisted repeatedly as
    // later mutations overwrite `requests[index].result`. Keep one logical
    // usage record per stable response identity and update it to the latest
    // persisted state instead of charging every physical JSONL line.
    let mut vscode_response_records: HashMap<String, usize> = HashMap::new();
    let mut line_index = 0usize;
    let mut line = Vec::with_capacity(16 * 1024);

    loop {
        line.clear();
        let bytes_read = match reader.read_until(b'\n', &mut line) {
            Ok(bytes_read) => bytes_read,
            Err(_) => {
                result.parse_errors += 1;
                break;
            }
        };
        if bytes_read == 0 {
            break;
        }

        line_index += 1;
        result.scanned_lines += 1;

        // Title resolution: the authoritative session name is `customTitle`.
        // Scan the header window for it and only fall back to a plain `title`
        // when no customTitle exists anywhere, so an early JSON-schema title
        // (e.g. the model's "Thinking Effort" label) can never win.
        if custom_title.is_none()
            && source == "copilot.cli.probe"
            && let Some(title) = extract_cli_user_title_from_line(&line)
        {
            custom_title = Some(title);
        } else if custom_title.is_none() && line_index <= 64 {
            if let Some(title) = extract_custom_title_from_line(&line) {
                custom_title = Some(title);
            } else if weak_title.is_none()
                && let Some(title) = extract_weak_title_from_line(&line)
            {
                weak_title = Some(title);
            }
        }

        if !is_usage_candidate_line(source, &line) {
            continue;
        }

        result.json_candidate_lines += 1;

        match serde_json::from_slice::<Value>(&line) {
            Ok(value) => {
                let mut extraction = LineExtraction::default();
                collect_line_extraction(&value, ContextFields::default(), &mut extraction);
                for raw in extraction.records {
                    let local =
                        enrich_from_response_metadata(raw.context, &extraction.response_metadata);
                    let record = UsageRecord {
                        source: source.to_owned(),
                        hostname: String::new(),
                        timestamp_ms: local.timestamp_ms,
                        local_time_hint: local.timestamp_ms.and_then(format_local_time),
                        chat_title: None,
                        model: raw.model,
                        model_id: local.model_id.as_deref().map(display_model_id),
                        credits: raw.credits,
                        details: raw.details,
                        session_id: local.session_id.clone().or_else(|| cli_session_id.clone()),
                        request_id: local.request_id.clone(),
                        response_id: local.response_id.clone(),
                        agent_id: local.agent_id.clone(),
                        project: project.clone(),
                        duration_ms: local.total_elapsed_ms,
                        turn_index: None,
                        session_total: None,
                        file: path.to_string_lossy().into_owned(),
                        line: line_index,
                    };
                    store_scanned_record(&mut result.records, &mut vscode_response_records, record);
                }
            }
            Err(_) => {
                result.parse_errors += 1;
                if let Ok(text) = std::str::from_utf8(&line) {
                    collect_records_from_text(source, path, line_index, text, &mut result.records);
                }
            }
        }
    }

    if let Some(title) = custom_title.or(weak_title) {
        for record in &mut result.records {
            record.chat_title = Some(title.clone());
        }
    }

    result
}

fn store_scanned_record(
    records: &mut Vec<UsageRecord>,
    vscode_response_records: &mut HashMap<String, usize>,
    record: UsageRecord,
) {
    if record.source == "vscode.chatSessions"
        && let Some(response_id) = record.response_id.clone()
    {
        if let Some(index) = vscode_response_records.get(&response_id).copied() {
            records[index] = record;
        } else {
            vscode_response_records.insert(response_id, records.len());
            records.push(record);
        }
    } else {
        records.push(record);
    }
}

fn cli_session_id_from_event_path(path: &Path) -> Option<String> {
    if !path
        .file_name()
        .is_some_and(|name| name.eq_ignore_ascii_case("events.jsonl"))
    {
        return None;
    }
    let session_dir = path.parent()?;
    let session_root = session_dir.parent()?;
    if !session_root
        .file_name()
        .is_some_and(|name| name.eq_ignore_ascii_case("session-state"))
    {
        return None;
    }
    session_dir
        .file_name()
        .map(|session_id| session_id.to_string_lossy().into_owned())
}

fn contains_bytes(haystack: &[u8], needle: &[u8]) -> bool {
    memmem::find(haystack, needle).is_some()
}

fn is_usage_candidate_line(source: &str, line: &[u8]) -> bool {
    if contains_bytes(line, b"credits") && contains_bytes(line, b"details") {
        return true;
    }

    source == "copilot.cli.probe"
        && contains_bytes(line, b"session.shutdown")
        && contains_bytes(line, b"modelMetrics")
}

fn collect_line_extraction(value: &Value, context: ContextFields, extraction: &mut LineExtraction) {
    match value {
        Value::Array(items) => {
            for item in items {
                collect_line_extraction(item, context.clone(), extraction);
            }
        }
        Value::Object(map) => {
            let mut local = context.clone();
            merge_context_from_object(&mut local, map);
            if let Some(Value::Object(metadata)) = map.get("metadata") {
                merge_context_from_object(&mut local, metadata);
            }

            if let Some(response_id) = local.response_id.clone() {
                let entry = extraction.response_metadata.entry(response_id).or_default();
                merge_context_missing(entry, &local);
            }

            if let Some(details) = map.get("details").and_then(Value::as_str)
                && let Some((model, credits)) = parse_credit_details(details)
            {
                extraction.records.push(RawUsageRecord {
                    context: local.clone(),
                    model,
                    credits,
                    details: details.to_owned(),
                });
            }

            collect_cli_shutdown_metrics(map, &local, extraction);

            for child in map.values() {
                collect_line_extraction(child, local.clone(), extraction);
            }
        }
        _ => {}
    }
}

fn collect_cli_shutdown_metrics(
    map: &serde_json::Map<String, Value>,
    context: &ContextFields,
    extraction: &mut LineExtraction,
) {
    if map.get("type").and_then(Value::as_str) != Some("session.shutdown") {
        return;
    }

    let Some(model_metrics) = map
        .get("data")
        .and_then(|data| data.get("modelMetrics"))
        .and_then(Value::as_object)
    else {
        return;
    };

    for (model, metrics) in model_metrics {
        let Some(credits) = metrics
            .get("requests")
            .and_then(|requests| requests.get("cost"))
            .and_then(value_as_f64)
        else {
            continue;
        };

        extraction.records.push(RawUsageRecord {
            context: context.clone(),
            model: model.clone(),
            credits,
            details: format!("Copilot CLI {model} • {credits} credits"),
        });
    }
}

fn value_as_f64(value: &Value) -> Option<f64> {
    match value {
        Value::Number(number) => number.as_f64(),
        _ => None,
    }
}

/// Returns the workspaceStorage/<hash> directory that owns a chatSessions file:
/// `.../workspaceStorage/<hash>/chatSessions/<id>.jsonl` -> `.../workspaceStorage/<hash>`.
fn workspace_dir_for_session(path: &Path) -> Option<PathBuf> {
    let chat_sessions = path.parent()?;
    if !chat_sessions
        .file_name()
        .is_some_and(|name| name.eq_ignore_ascii_case("chatSessions"))
    {
        return None;
    }
    Some(chat_sessions.parent()?.to_path_buf())
}

/// Reads each workspace's `workspace.json` once and maps the storage directory
/// to a friendly project name (the last segment of the opened folder/workspace).
fn build_project_map(files: &[PathBuf]) -> HashMap<PathBuf, String> {
    let mut map: HashMap<PathBuf, String> = HashMap::new();
    let mut dirs: std::collections::BTreeSet<PathBuf> = std::collections::BTreeSet::new();
    for file in files {
        if let Some(dir) = workspace_dir_for_session(file) {
            dirs.insert(dir);
        }
    }
    for dir in dirs {
        if let Some(name) = read_project_name(&dir) {
            map.insert(dir, name);
        }
    }
    map
}

fn read_project_name(workspace_dir: &Path) -> Option<String> {
    let text = fs::read_to_string(workspace_dir.join("workspace.json")).ok()?;
    let value: Value = serde_json::from_str(&text).ok()?;
    let object = value.as_object()?;
    if let Some(folder) = object.get("folder").and_then(Value::as_str) {
        return project_name_from_uri(folder, false);
    }
    if let Some(workspace) = object.get("workspace").and_then(Value::as_str) {
        return project_name_from_uri(workspace, true);
    }
    None
}

/// Extracts a human-readable project name from a VS Code file URI.
/// `file:///c%3A/Scripts/projects/opendecknew` -> `opendecknew`.
/// A `.code-workspace` file URI returns the file stem.
fn project_name_from_uri(uri: &str, is_workspace_file: bool) -> Option<String> {
    let without_scheme = uri.strip_prefix("file://").unwrap_or(uri);
    let decoded = percent_decode(without_scheme);
    let trimmed = decoded.trim_end_matches(['/', '\\']);
    let last = trimmed
        .rsplit(['/', '\\'])
        .find(|segment| !segment.is_empty())?;
    let name = if is_workspace_file {
        last.strip_suffix(".code-workspace").unwrap_or(last)
    } else {
        last
    }
    .trim();
    if name.is_empty() {
        None
    } else {
        Some(name.to_owned())
    }
}

/// Minimal percent-decoding sufficient for VS Code workspace URIs.
fn percent_decode(input: &str) -> String {
    let bytes = input.as_bytes();
    let mut out: Vec<u8> = Vec::with_capacity(bytes.len());
    let mut index = 0;
    while index < bytes.len() {
        if bytes[index] == b'%' && index + 2 < bytes.len() {
            let hi = (bytes[index + 1] as char).to_digit(16);
            let lo = (bytes[index + 2] as char).to_digit(16);
            if let (Some(hi), Some(lo)) = (hi, lo) {
                out.push((hi * 16 + lo) as u8);
                index += 3;
                continue;
            }
        }
        out.push(bytes[index]);
        index += 1;
    }
    String::from_utf8_lossy(&out).into_owned()
}

/// Assigns a 1-based `turn_index` within each parent session plus the session's
/// total exchange count. Records must already be ordered chronologically within
/// each `(hostname, session_id)` group, which both the scan and merge sorts
/// guarantee.
fn assign_turn_indices(records: &mut [UsageRecord]) {
    // Replayed VS Code and SQLite-backed CLI records carry user-facing turns.
    // Preserve those values; only synthesize sequential positions for legacy
    // VS Code/CLI records where no turn was recorded at all.
    let mut explicit_totals: HashMap<(String, String), u32> = HashMap::new();
    let mut implicit_totals: HashMap<(String, String), u32> = HashMap::new();
    for record in records.iter() {
        if is_cli_session_summary(record) {
            continue;
        }
        if let Some(session) = record.session_id.as_ref() {
            let key = (record.hostname.clone(), session.clone());
            if let Some(turn) = record.turn_index {
                let known_total = record.session_total.unwrap_or(turn).max(turn);
                explicit_totals
                    .entry(key)
                    .and_modify(|total| *total = (*total).max(known_total))
                    .or_insert(known_total);
            } else {
                *implicit_totals.entry(key).or_default() += 1;
            }
        }
    }
    let mut seen: HashMap<(String, String), u32> = HashMap::new();
    for record in records.iter_mut() {
        if is_cli_session_summary(record) {
            record.turn_index = None;
            record.session_total = None;
            continue;
        }
        let Some(session) = record.session_id.clone() else {
            record.turn_index = None;
            record.session_total = None;
            continue;
        };
        let key = (record.hostname.clone(), session);
        if record.turn_index.is_some() {
            record.session_total = explicit_totals.get(&key).copied();
            continue;
        }
        let counter = seen.entry(key.clone()).or_default();
        *counter += 1;
        record.turn_index = Some(*counter);
        record.session_total = implicit_totals.get(&key).copied();
    }
}

fn is_cli_session_summary(record: &UsageRecord) -> bool {
    record.source.starts_with("copilot.cli")
        && (record.details.contains("legacy session shutdown")
            || (record.source == "copilot.cli.probe" && record.request_id.is_none()))
}

fn merge_context_from_object(context: &mut ContextFields, map: &serde_json::Map<String, Value>) {
    assign_string(&mut context.session_id, map, "sessionId");
    assign_string(&mut context.request_id, map, "requestId");
    assign_string(&mut context.response_id, map, "responseId");
    assign_string(&mut context.model_id, map, "modelId");
    assign_string(&mut context.agent_id, map, "agentId");

    if context.timestamp_ms.is_none() {
        context.timestamp_ms = map.get("timestamp").and_then(|value| {
            value
                .as_i64()
                .or_else(|| value.as_str().and_then(parse_rfc3339_timestamp_ms))
        });
    }

    if let Some(Value::Object(model_state)) = map.get("modelState")
        && let Some(completed_at) = model_state.get("completedAt").and_then(Value::as_i64)
    {
        context.timestamp_ms = Some(completed_at);
    }

    if let Some(completed_at) = map.get("completedAt").and_then(Value::as_i64) {
        context.timestamp_ms = Some(completed_at);
    }

    // The chat-session `result` node carries wall-clock timing for the whole
    // exchange (request submitted -> response completed) under `timings`.
    if context.total_elapsed_ms.is_none()
        && let Some(Value::Object(timings)) = map.get("timings")
        && let Some(elapsed) = timings.get("totalElapsed").and_then(Value::as_i64)
        && elapsed > 0
    {
        context.total_elapsed_ms = Some(elapsed);
    }
}

fn parse_rfc3339_timestamp_ms(timestamp: &str) -> Option<i64> {
    DateTime::parse_from_rfc3339(timestamp)
        .ok()
        .map(|time| time.timestamp_millis())
}

fn assign_string(target: &mut Option<String>, map: &serde_json::Map<String, Value>, key: &str) {
    if target.is_none()
        && let Some(value) = map.get(key).and_then(Value::as_str)
    {
        *target = Some(value.to_owned());
    }
}

fn parse_credit_details(details: &str) -> Option<(String, f64)> {
    let trimmed = details.trim();
    let before_suffix = trimmed
        .strip_suffix(" credits")
        .or_else(|| trimmed.strip_suffix(" credit"))?;
    let mut parts = before_suffix.rsplitn(2, char::is_whitespace);
    let credits_text = parts.next()?.trim();
    let model_part = parts.next()?.trim();

    let credits = credits_text.parse::<f64>().ok()?;
    let model = model_part
        .trim_end_matches(|ch: char| {
            ch.is_whitespace() || !(ch.is_ascii_alphanumeric() || ch == ')' || ch == ']')
        })
        .trim()
        .to_owned();

    if model.is_empty() || !credits.is_finite() || credits < 0.0 {
        None
    } else {
        Some((model, credits))
    }
}

fn display_model_id(model_id: &str) -> String {
    model_id
        .strip_prefix("copilot/")
        .unwrap_or(model_id)
        .to_owned()
}

fn format_local_time(timestamp_ms: i64) -> Option<String> {
    let utc = DateTime::<Utc>::from_timestamp_millis(timestamp_ms)?;
    Some(
        utc.with_timezone(&Local)
            .format("%Y-%m-%d %H:%M:%S")
            .to_string(),
    )
}

fn format_local_day(timestamp_ms: i64) -> Option<String> {
    let utc = DateTime::<Utc>::from_timestamp_millis(timestamp_ms)?;
    Some(utc.with_timezone(&Local).format("%Y-%m-%d").to_string())
}

fn collect_records_from_text(
    source: &str,
    path: &Path,
    line_number: usize,
    line: &str,
    records: &mut Vec<UsageRecord>,
) {
    let Some(details_key_index) = line.find("details") else {
        return;
    };
    let Some(credits_index) = line[details_key_index..].find("credits") else {
        return;
    };

    let end = details_key_index + credits_index + "credits".len();
    let start = line[..details_key_index]
        .rfind('"')
        .map(|index| index + 1)
        .unwrap_or(details_key_index);
    let candidate = &line[start..end];

    if let Some((model, credits)) = parse_credit_details(candidate) {
        records.push(UsageRecord {
            source: source.to_owned(),
            hostname: String::new(),
            timestamp_ms: None,
            local_time_hint: None,
            chat_title: None,
            model,
            model_id: None,
            credits,
            details: candidate.to_owned(),
            session_id: None,
            request_id: None,
            response_id: None,
            agent_id: None,
            project: None,
            duration_ms: None,
            turn_index: None,
            session_total: None,
            file: path.to_string_lossy().into_owned(),
            line: line_number,
        });
    }
}

fn write_csv(path: &Path, records: &[UsageRecord], emit_bom: bool) -> Result<()> {
    if path.as_os_str() == "-" {
        let mut writer = csv::Writer::from_writer(std::io::stdout());
        for record in records {
            writer.serialize(record)?;
        }
        writer.flush()?;
        return Ok(());
    }

    let mut file = File::create(path)
        .with_context(|| format!("failed to create CSV output {}", path.display()))?;
    if emit_bom {
        file.write_all(b"\xEF\xBB\xBF")?;
    }

    let mut writer = csv::Writer::from_writer(file);
    for record in records {
        writer.serialize(record)?;
    }
    writer.flush()?;
    Ok(())
}

fn write_json(path: &Path, records: &[UsageRecord], emit_bom: bool) -> Result<()> {
    if path.as_os_str() == "-" {
        println!("{}", serde_json::to_string_pretty(records)?);
        return Ok(());
    }

    let mut file = File::create(path)
        .with_context(|| format!("failed to create JSON output {}", path.display()))?;
    if emit_bom {
        file.write_all(b"\xEF\xBB\xBF")?;
    }
    serde_json::to_writer_pretty(file, records)?;
    Ok(())
}

fn enrich_from_response_metadata(
    mut local: ContextFields,
    response_metadata: &HashMap<String, ContextFields>,
) -> ContextFields {
    if let Some(response_id) = local.response_id.as_ref()
        && let Some(metadata) = response_metadata.get(response_id)
    {
        merge_context_missing(&mut local, metadata);
    }
    local
}

fn merge_context_missing(target: &mut ContextFields, source: &ContextFields) {
    if target.session_id.is_none() {
        target.session_id = source.session_id.clone();
    }
    if target.request_id.is_none() {
        target.request_id = source.request_id.clone();
    }
    if target.response_id.is_none() {
        target.response_id = source.response_id.clone();
    }
    if target.model_id.is_none() {
        target.model_id = source.model_id.clone();
    }
    if target.agent_id.is_none() {
        target.agent_id = source.agent_id.clone();
    }
    if target.timestamp_ms.is_none() {
        target.timestamp_ms = source.timestamp_ms;
    }
    if target.total_elapsed_ms.is_none() {
        target.total_elapsed_ms = source.total_elapsed_ms;
    }
}

fn extract_custom_title(value: &Value) -> Option<String> {
    let object = value.as_object()?;
    let key = object.get("k")?.as_array()?;
    let is_custom_title = key
        .iter()
        .any(|part| part.as_str().is_some_and(|text| text == "customTitle"));
    if !is_custom_title {
        return None;
    }

    object
        .get("v")
        .and_then(Value::as_str)
        .map(str::trim)
        .filter(|title| !title.is_empty())
        .map(ToOwned::to_owned)
}

/// Best-effort byte-level scan for the chat title without parsing the entire
/// session document. Handles both shapes we have seen:
///   - delta jsonl header   : {"k":["customTitle"],"v":"…"}
///   - single-object session: {"kind":0,"v":{"customTitle":"…", "title":"…", …}}
#[cfg(test)]
fn quick_extract_title_from_line(line: &[u8]) -> Option<String> {
    const NEEDLES: [&[u8]; 2] = [b"\"customTitle\":\"", b"\"title\":\""];
    for needle in NEEDLES {
        if let Some(title) = extract_json_string_after(line, needle) {
            return Some(title);
        }
    }
    None
}

/// Walks the bytes after `needle` (which must end at the opening quote of a JSON
/// string) and decodes the first complete JSON string literal that follows.
fn extract_json_string_after(line: &[u8], needle: &[u8]) -> Option<String> {
    let mut search_from = 0;
    while let Some(rel) = memmem::find(&line[search_from..], needle) {
        let start = search_from + rel;
        // Include the opening quote so serde_json can decode the literal.
        let literal_start = start + needle.len() - 1;
        let mut cursor = literal_start + 1;
        while cursor < line.len() {
            let byte = line[cursor];
            if byte == b'\\' {
                cursor += 2;
                continue;
            }
            if byte == b'"' {
                break;
            }
            cursor += 1;
        }
        if cursor >= line.len() {
            break;
        }
        let literal = &line[literal_start..=cursor];
        if let Ok(text) = std::str::from_utf8(literal)
            && let Ok(decoded) = serde_json::from_str::<String>(text)
        {
            let trimmed = decoded.trim();
            if !trimmed.is_empty() {
                return Some(trimmed.to_owned());
            }
        }
        search_from = cursor + 1;
    }
    None
}

/// Extracts the authoritative session `customTitle` from a single line, covering
/// both the inline (`"customTitle":"…"`) and delta (`{"k":["customTitle"],"v":…}`)
/// shapes.
fn extract_custom_title_from_line(line: &[u8]) -> Option<String> {
    if let Some(title) = extract_json_string_after(line, b"\"customTitle\":\"") {
        return Some(title);
    }
    if contains_bytes(line, b"customTitle")
        && let Ok(value) = serde_json::from_slice::<Value>(line)
        && let Some(title) = extract_custom_title(&value)
    {
        return Some(title);
    }
    None
}

fn extract_cli_user_title_from_line(line: &[u8]) -> Option<String> {
    if !contains_bytes(line, b"user.message") || !contains_bytes(line, b"content") {
        return None;
    }
    let value = serde_json::from_slice::<Value>(line).ok()?;
    let object = value.as_object()?;
    if object.get("type").and_then(Value::as_str) != Some("user.message")
        || object
            .get("agentId")
            .and_then(Value::as_str)
            .is_some_and(|agent| !agent.is_empty())
    {
        return None;
    }
    let data = object.get("data")?.as_object()?;
    if data.get("source").is_some_and(|source| !source.is_null()) {
        return None;
    }
    normalized_cli_title(data.get("content").and_then(Value::as_str))
}

/// Extracts a plain `"title"` as a weak fallback, skipping JSON-schema lines
/// (e.g. a model's `{"reasoningEffort":{"title":"Thinking Effort","enum":[…]}}`)
/// whose `title` is a UI label, not the session title.
fn extract_weak_title_from_line(line: &[u8]) -> Option<String> {
    if contains_bytes(line, b"\"enum\"")
        || contains_bytes(line, b"\"properties\"")
        || contains_bytes(line, b"reasoningEffort")
    {
        return None;
    }
    extract_json_string_after(line, b"\"title\":\"")
}

fn detect_hostname() -> String {
    if let Some(name) = env::var("COMPUTERNAME")
        .ok()
        .or_else(|| env::var("HOSTNAME").ok())
        .map(|name| sanitize_hostname(&name))
        .filter(|name| !name.is_empty())
    {
        return name;
    }

    #[cfg(unix)]
    {
        for path in ["/proc/sys/kernel/hostname", "/etc/hostname"] {
            if let Ok(text) = fs::read_to_string(path) {
                let cleaned = sanitize_hostname(&text);
                if !cleaned.is_empty() {
                    return cleaned;
                }
            }
        }
    }

    "unknown-host".to_owned()
}

fn sanitize_hostname(raw: &str) -> String {
    raw.trim()
        .chars()
        .map(|ch| {
            if ch.is_ascii_alphanumeric() || ch == '-' || ch == '_' || ch == '.' {
                ch
            } else {
                '-'
            }
        })
        .collect::<String>()
        .trim_matches('-')
        .to_owned()
}

fn default_output_path(hostname: &str, format: OutputFormat) -> PathBuf {
    let extension = match format {
        OutputFormat::Csv => "csv",
        OutputFormat::Json => "json",
    };
    PathBuf::from(format!("copilot-usage-{hostname}.{extension}"))
}

fn default_html_path(output_path: &Path, hostname: &str) -> PathBuf {
    // Place the HTML next to the primary output file, replacing the extension.
    let mut candidate = output_path.to_path_buf();
    if candidate.set_extension("html") {
        return candidate;
    }
    PathBuf::from(format!("copilot-usage-{hostname}.html"))
}

const REPORT_TEMPLATE: &str = include_str!("report-template.html");
const REPORT_DATA_PLACEHOLDER: &str = "__GH_USAGE_DATA__";
const REPORT_SNAPDOM: &str = include_str!("snapdom.js");
const REPORT_SNAPDOM_PLACEHOLDER: &str = "__GH_USAGE_SNAPDOM__";

fn write_html(path: &Path, records: &[UsageRecord], primary_host: &str) -> Result<()> {
    let payload = serde_json::json!({
        "generatedAt": Local::now().format("%Y-%m-%d %H:%M:%S").to_string(),
        "primaryHost": primary_host,
        "records": records,
    });

    let mut data = serde_json::to_string(&payload)?;
    // Avoid prematurely closing the inline <script> block. JSON has no literal "</",
    // so any "</" inside string values is escaped to "<\/" which is still valid JSON.
    data = data.replace("</", "<\\/");

    // Inject the snapdom library first (its own <script> block), then the JSON
    // data. The library is inserted verbatim and is NOT subject to the data escaping.
    let html = REPORT_TEMPLATE
        .replace(REPORT_SNAPDOM_PLACEHOLDER, REPORT_SNAPDOM)
        .replace(REPORT_DATA_PLACEHOLDER, &data);

    let mut file = File::create(path)
        .with_context(|| format!("failed to create HTML output {}", path.display()))?;
    file.write_all(html.as_bytes())?;
    Ok(())
}

