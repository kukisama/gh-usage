#[derive(Debug, Parser)]
#[command(name = "gh-usage")]
#[command(
    about = "Scan local GitHub Copilot / VS Code Chat usage records and export credit usage as CSV",
    version
)]
struct Cli {
    /// VS Code workspaceStorage root. Defaults to the standard VS Code user-data path for the current OS.
    #[arg(long)]
    vscode_workspace_storage: Option<PathBuf>,

    /// Copilot CLI root. Defaults to ~/.copilot.
    #[arg(long)]
    copilot_cli_root: Option<PathBuf>,

    /// Include Copilot CLI records (kept for compatibility; CLI scanning is now enabled by default).
    #[arg(long, hide = true)]
    include_cli_logs: bool,

    /// Skip Copilot CLI records and only scan VS Code chat sessions.
    #[arg(long)]
    no_cli_logs: bool,

    /// Only scan files modified within N days.
    #[arg(long)]
    since_days: Option<u64>,

    /// Maximum files to scan, useful while experimenting.
    #[arg(long)]
    max_files: Option<usize>,

    /// Output CSV path. Use '-' for stdout. Defaults to copilot-usage-<hostname>.csv beside the binary's working directory.
    #[arg(long, short)]
    output: Option<PathBuf>,

    /// Output format. CSV is the default for spreadsheet inspection.
    #[arg(long, value_enum, default_value_t = OutputFormat::Csv)]
    format: OutputFormat,

    /// Override the machine hostname embedded into records. Defaults to the detected OS hostname.
    #[arg(long)]
    hostname: Option<String>,

    /// Explicit path for the HTML summary report. Implies HTML output. Defaults to copilot-usage-<hostname>.html beside the CSV.
    #[arg(long)]
    html: Option<PathBuf>,

    /// Skip writing the HTML summary report. HTML is generated by default whenever a file output is produced.
    #[arg(long)]
    no_html: bool,

    /// Generate HTML and open it with the default browser, without a keypress pause.
    /// Also accepts `gh-usage -view` (as the first argument).
    #[arg(long, short = 'v', conflicts_with = "no_html")]
    view: bool,

    /// Print a short summary to stderr after writing output.
    #[arg(long)]
    summary: bool,

    /// Do not write a UTF-8 BOM for file output. By default files include BOM for Windows Excel compatibility.
    #[arg(long)]
    no_bom: bool,

    /// Also export an auditable Markdown report of local human submissions in half-hour slots (UTC+08:00).
    #[arg(long, value_name = "PATH", conflicts_with = "merge")]
    effort_report: Option<PathBuf>,

    /// Do not export or include human effort events.
    #[arg(long, conflicts_with = "effort_report")]
    no_effort: bool,

    /// Limit the effort report to exact project names; repeat to combine projects.
    #[arg(long, value_name = "NAME", requires = "effort_report")]
    effort_project: Vec<String>,

    /// Rebuild HTML from one usage CSV and its companion effort CSV, without scanning local logs.
    #[arg(long, value_name = "CSV", conflicts_with_all = ["merge", "no_html", "output", "effort_report"])]
    from_csv: Option<PathBuf>,

    /// Merge one standard-named CSV export per machine in DIR (default: current directory), without scanning local logs.
    #[arg(long, value_name = "DIR", num_args = 0..=1, default_missing_value = ".", conflicts_with = "output")]
    merge: Option<PathBuf>,
}

#[derive(Debug, Clone, Copy, ValueEnum)]
enum OutputFormat {
    Csv,
    Json,
}

// Only normalize the leading convenience spelling. Never rewrite option values
// (e.g. --hostname -view) or anything following the `--` separator.
fn normalize_view_args(
    args: impl IntoIterator<Item = impl Into<std::ffi::OsString>>,
) -> Vec<std::ffi::OsString> {
    let mut args: Vec<_> = args.into_iter().map(Into::into).collect();
    if let Some(arg) = args.get_mut(1)
        && arg == "-view"
    {
        *arg = "--view".into();
    }
    args
}

fn resolve_html_path(cli: &Cli, output: &Path, hostname: &str) -> Option<PathBuf> {
    if cli.no_html {
        None
    } else if let Some(path) = &cli.html {
        Some(path.clone())
    } else if output.as_os_str() == "-" {
        cli.view.then(|| PathBuf::from(format!("copilot-usage-{hostname}.html")))
    } else {
        Some(default_html_path(output, hostname))
    }
}

fn default_output_path(hostname: &str, format: OutputFormat) -> PathBuf {
    match format {
        OutputFormat::Csv => PathBuf::from(export::usage_csv_name(hostname)),
        OutputFormat::Json => PathBuf::from(format!("copilot-usage-{hostname}.json")),
    }
}

fn default_html_path(output_path: &Path, hostname: &str) -> PathBuf {
    // Place the HTML next to the primary output file, replacing the extension.
    let mut candidate = output_path.to_path_buf();
    if candidate.set_extension("html") {
        return candidate;
    }
    PathBuf::from(format!("copilot-usage-{hostname}.html"))
}

fn main() -> Result<()> {
    let total_started = Instant::now();
    let effort_until = effort::end_of_collection();
    let no_args = env::args_os().len() == 1;
    let double_clicked = no_args && platform::launched_from_explorer();
    let cli = Cli::parse_from(normalize_view_args(env::args_os()));

    if let Some(csv) = cli.from_csv.as_deref() {
        let html = cli.html.clone().unwrap_or_else(|| csv.with_extension("html"));
        report::render_csv(&html, csv, !cli.no_effort, None)?;
        if cli.view { platform::open_path(&html)?; }
        return Ok(());
    }
    if let Some(dir) = cli.merge.as_deref() {
        return merge::run_merge(dir, double_clicked, cli.view, cli.html.as_deref(), cli.no_effort);
    }

    let hostname = cli.hostname.as_deref()
        .map(platform::sanitize_hostname)
        .filter(|name| !name.is_empty())
        .unwrap_or_else(platform::detect_hostname);
    let output = cli.output.clone().unwrap_or_else(|| default_output_path(&hostname, cli.format));
    let html = resolve_html_path(&cli, &output, &hostname);
    let format = match cli.format {
        OutputFormat::Csv => app::UsageFormat::Csv,
        OutputFormat::Json => app::UsageFormat::Json,
    };
    let outputs = app::OutputPaths::new(output, html, cli.effort_report, format, cli.no_effort)?;

    let vscode_root = cli.vscode_workspace_storage
        .or_else(platform::default_vscode_workspace_storage)
        .context("Could not determine VS Code workspaceStorage path; pass --vscode-workspace-storage")?;
    let cli_root = if !cli.no_cli_logs || cli.include_cli_logs {
        cli.copilot_cli_root.or_else(platform::default_copilot_cli_root)
    } else {
        None
    };

    app::run_scan(app::ScanOptions {
        outputs,
        hostname: &hostname,
        vscode_root: &vscode_root,
        cli_root: cli_root.as_deref(),
        cutoff: cli.since_days.map(time::cutoff_system_time),
        max_files: cli.max_files,
        effort_projects: &cli.effort_project,
        total_started,
        effort_until,
        emit_bom: !cli.no_bom,
        summary: no_args || cli.summary,
        view: cli.view,
        double_clicked,
    })
}
